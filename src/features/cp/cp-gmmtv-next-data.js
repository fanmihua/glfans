// All four Be Mine pairings share one project and poster. Their chapters are
// descriptive metadata, not four invented independent series or premiere dates.
export function addGmmtvNextProjects(cp) {
  const additions = gmmtvNextProjects.filter(project => project.cpIds.includes(cp.id)).map(project => ({
    ...project,
    ...(project.id === 'be-mine' ? {
      ensemble: true, chapter: chapters[cp.id],
      storyNote: { zh: `《Be Mine》群像篇章：${chapters[cp.id]}`, en: `Be Mine anthology chapter: ${chapters[cp.id]}`, th: `เรื่องย่อยใน Be Mine: ${chapters[cp.id]}` },
    } : {}),
  }));
  if (!additions.length) return cp;
  return { ...cp, checkedAt: '2026-11-04', upcoming: [
    ...(cp.upcoming || []).filter(work => !additions.some(project => project.id === work.id)), ...additions,
  ] };
}
